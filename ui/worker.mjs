import {simulate} from '../core/engine.mjs';
import {forecast} from '../core/forecast.mjs';
import {compareBanners} from '../core/compare.mjs';
import {simulatePlayers} from '../core/players.mjs';
import {simulateFlow} from '../core/flow.mjs';
import {balanceBanner} from '../core/balance.mjs';
self.onmessage=e=>{try{const {type,args}=e.data;const progress=p=>self.postMessage({progress:p});let result;
  if(type==='analyze')result=forecast(...args,progress);
  else if(type==='compare')result=compareBanners(...args,progress);
  else if(type==='players')result=simulatePlayers(args[0],args[1],{...args[2],onProgress:progress});
  else if(type==='flow')result=simulateFlow(...args,progress);
  else if(type==='balance')result=balanceBanner(...args,progress);
  else if(type==='simulate')result=simulate(args[0],args[1],{...args[2],onProgress:progress});
  else throw Error('Tác vụ không hợp lệ.');
  self.postMessage({result});}catch(error){self.postMessage({error:error.message});}};
